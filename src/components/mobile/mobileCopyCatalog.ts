/** Copy that mobile surfaces are allowed to render straight from source. */
export type MobileCopyKey = keyof typeof MOBILE_ARABIC;

export function mobileCopy(text: string, locale: 'en' | 'ar'): string {
  if (locale !== 'ar') return text;
  return MOBILE_ARABIC[text] ?? text;
}

/** Used by the regression test that keeps Arabic labels from rotting. */
export function mobileCopyCoverage(): { total: number; filled: number; missing: string[] } {
  const entries = Object.entries(MOBILE_ARABIC);
  const missing = entries.filter(([, value]) => value.trim().length === 0).map(([key]) => key);
  return { total: entries.length, filled: entries.length - missing.length, missing };
}
