/**
 * Create ICO file (Windows icon format)
 * Minimal valid ICO: single 1x1 image
 */
function createMinimalICO() {
  // ICO header + minimal image directory entry + image data
  const ico = Buffer.from([
    0x00, 0x00,             // Reserved (0)
    0x01, 0x00,             // Type: 1 (icon)
    0x01, 0x00,             // Count: 1 image
    // Image directory entry
    0x20, 0x20, 0x00, 0x00, // Width x Height (32x32)
    0x00, 0x00, 0x00, 0x00, // Color count, reserved
    0x01, 0x00,             // Color planes
    0x18, 0x00,             // Bits per pixel (24)
    0x00, 0x01, 0x00, 0x00, // Bytes in image
    0x16, 0x00, 0x00, 0x00, // Offset to image data (22)
    // Minimal BMP data (1x1 pixel)
    0x28, 0x00, 0x00, 0x00, // Header size
    0x01, 0x00, 0x00, 0x00, // Width
    0x02, 0x00, 0x00, 0x00, // Height
    0x01, 0x00, 0x18, 0x00, // Planes, bits
    0x00, 0x00, 0x00, 0x00, // Compression
    0x00, 0x00, 0x00, 0x00, // Image size
    0x00, 0x00, 0x00, 0x00, // X pixels/meter
    0x00, 0x00, 0x00, 0x00, // Y pixels/meter
    0x00, 0x00, 0x00, 0x00, // Colors used
    0x00, 0x00, 0x00, 0x00, // Important colors
    0x00, 0x00, 0x00,       // Pixel data (black)
    0x00, 0x00, 0x00,       // Pixel data (black)
  ]);
  return ico;
}

