/**
 * Create macOS ICNS file
 * Minimal valid ICNS: 'ic04' (16x16) chunk
 */
function createMinimalICNS() {
  // ICNS header
  const icns = Buffer.from([
    0x69, 0x63, 0x6e, 0x73, // Magic: 'icns'
    0x00, 0x00, 0x00, 0x20, // File size: 32 bytes total
    0x69, 0x63, 0x30, 0x34, // Type: 'ic04' (16x16 4-bit)
    0x00, 0x00, 0x00, 0x18, // Chunk size: 24 bytes
    // 16x16 minimal image data (all zeros = transparent)
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  ]);
  return icns;
}

